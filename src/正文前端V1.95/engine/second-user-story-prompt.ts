export type StoryPromptChatMessage = {
  message_id: number;
  role: string;
  is_hidden?: boolean;
  message?: string;
};

export function resolveStoryPromptSourceUserMessage(messages: readonly StoryPromptChatMessage[]) {
  const visibleMessages = messages.filter(message => message.is_hidden !== true);
  const latestMessage = visibleMessages.at(-1);
  if (
    latestMessage?.role !== 'user' ||
    latestMessage.message_id !== SECOND_USER_STORY_SOURCE_MESSAGE_ID
  ) {
    return null;
  }

  return latestMessage;
}

export function resolveStoryPromptPrearmAssistantMessage(messages: readonly StoryPromptChatMessage[]) {
  const visibleMessages = messages.filter(message => message.is_hidden !== true);
  const latestMessage = visibleMessages.at(-1);
  if (
    latestMessage?.role !== 'assistant' ||
    latestMessage.message_id !== SECOND_USER_STORY_PREARM_MESSAGE_ID
  ) {
    return null;
  }

  return latestMessage;
}

export function shouldPrearmSecondUserStoryPrompt(messages: readonly StoryPromptChatMessage[]) {
  return resolveStoryPromptPrearmAssistantMessage(messages) !== null;
}

export function shouldInjectSecondUserStoryPrompt(messages: readonly StoryPromptChatMessage[]) {
  return resolveStoryPromptSourceUserMessage(messages) !== null;
}

export function resolveStoryPromptGenerationSourceUserMessage(messages: readonly StoryPromptChatMessage[]) {
  const visibleMessages = messages.filter(message => message.is_hidden !== true);
  const latestMessage = visibleMessages.at(-1);
  if (latestMessage?.role === 'user' && latestMessage.message_id === SECOND_USER_STORY_SOURCE_MESSAGE_ID) {
    return latestMessage;
  }

  const isEmptyFourthMessagePlaceholder =
    latestMessage?.role === 'assistant' &&
    latestMessage.message_id === SECOND_USER_STORY_SOURCE_MESSAGE_ID + 1 &&
    typeof latestMessage.message === 'string' &&
    latestMessage.message.trim().length === 0;
  if (!isEmptyFourthMessagePlaceholder) {
    return null;
  }

  const sourceUserMessage = visibleMessages.at(-2);
  return sourceUserMessage?.role === 'user' && sourceUserMessage.message_id === SECOND_USER_STORY_SOURCE_MESSAGE_ID
    ? sourceUserMessage
    : null;
}

export function shouldInjectSecondUserStoryPromptForGeneration(
  type: string,
  dryRun: boolean,
  messages: readonly StoryPromptChatMessage[],
) {
  const normalizedType = String(type ?? '').trim().toLowerCase();
  if (dryRun || normalizedType === 'quiet' || normalizedType === 'impersonate') {
    return false;
  }

  return resolveStoryPromptGenerationSourceUserMessage(messages) !== null;
}

export function resolveSecondUserStoryPrompt(userRoleName: string | null | undefined) {
  return userRoleName === '小夜月静夜' ? SECOND_USER_SHIZUYA_STORY_PROMPT : SECOND_USER_STORY_PROMPT;
}
